const tests = [
  '딤후3:1-2 "너는 이것을 알라 말세에 고통하는 때가 이르러"',
  '삿21:25 "그 때에 이스라엘에 왕이 없으므로"',
  '시145:1 "왕이신 나의 하나님이여"',
  '롬5:8,10 "우리가 아직 죄인 되었을 때에"',
  '요일1:7b "그 아들 예수의 피가"',
  '딛3:5 "우리를 구원하시되"',
]

const r = /^([가-힣]{1,4}\d+:\d+[\d\-,b]*)\s+([""\u201c].+)$/

for (const t of tests) {
  const m = t.match(r)
  console.log(t.substring(0, 10), '->', m ? `ref="${m[1]}" quote="${m[2].substring(0,10)}..."` : 'NO MATCH')
}
